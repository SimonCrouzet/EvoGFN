r"""The transfer probe: does a policy's knowledge survive a moved anchor?

The pre-declared specification is ``notes/experiments/transfer-probe.md`` and the
implementation plan drawn from it is ``notes/experiments/transfer-probe-plan.md``.
Neither is restated here. What is here is the machinery those two ask for, and --
at length, because a deviation from a pre-declared specification has to be
visible and argued rather than silent -- the five places this module does
something the specification does not say.

## What the probe measures

A GFlowNet fits $P(a \mid s)$, which is a property of the landscape rather than of
the parent, so its knowledge should remain valid when the anchor moves. A genetic
algorithm's representation of *where it is* **is** its population, and CMA-ES's
mean is parameterised relative to the parent it was fitted around. The probe
measures that directly instead of waiting for it to compound over a campaign:
train at anchor A, move to anchor B, and measure the first round at B **before
any new learning**.

## Why this is a new module and imports nothing new into the old ones

Roughly sixteen thousand stored records name
[evogfn.benchmark.suite][]'s ``RESULT_DEPENDENCIES`` closure, which is 48 modules
and contains every file this probe would naturally want to extend --
[evogfn.benchmark.attainable][], [evogfn.algorithms.gflownet.sampler][],
[evogfn.models.policy][], [evogfn.landscapes.ehrlich][],
[evogfn.loop.campaign][]. The fingerprint hashes raw file bytes, so a one-line
addition to any of them makes every one of those records stale and re-runnable
at a cost measured in machine-weeks.

[RunRecord.stale_against][evogfn.benchmark.store.RunRecord.stale_against] only
ever compares the names a record stored, and
[dependency_closure][evogfn.benchmark.store.dependency_closure] only reaches a
module something imports. So a new file that imports *from* the tree and is
imported *by* nothing is fingerprint-inert, and this is that file. **Nothing in
``benchmark/suite.py``, ``benchmark/methods.py``, ``benchmark/selection.py`` or
``loop/campaign.py`` may import it**, or every result in the store goes stale on
the next edit to the probe.

The cost of that rule is paid twice below, and both places say so where they
occur: `anchor_attainable` reaches into two private helpers of
[evogfn.benchmark.attainable][] rather than adding a public entry point to it,
and `_policy` mirrors ``methods._policy`` rather than importing it.

## Deviation 1, and the one that changes what is measured: one shared surrogate

**Every arm at anchor B screens its candidate pool with the same surrogate. No
exceptions, no per-arm variants.** It is fitted at anchor A on random-mutagenesis
data at the same oracle budget a training campaign spends --
`INDEPENDENT_DATASET` -- so it was generated by none of the policies under test.
The three transferred rungs, `plain-fresh`, `plain-retrained`, `random` and every
classical rung all read their own pool through it.

The specification says otherwise: each transferred arm carries the surrogate its
own campaign fitted, and `plain-fresh` and `random` carry none. Three arguments
against that, in the order they bite.

**Screening must be identical or the probe measures two things.** With one screen
over every arm, a difference in measured plate quality can only come from which
candidates the proposer generated -- which is the single thing the probe exists
to measure. Under per-arm surrogates the plate is selected by a different model
for every row, and "best in plate" mixes policy transfer with surrogate quality.

**No arm's own surrogate can be the shared one.** A model fitted on one policy's
trajectories has seen exactly the region that policy explores, so it judges that
policy's proposals in-distribution and another's possibly not, and would
systematically screen its own pool better. Designating any arm's model therefore
favours that arm. Only a model fitted on data no proposer generated is neutral,
and that is what this is.

**It removes an asymmetry sitting directly under criterion 1.** `plain-fresh` and
`random` ran no campaign at A and so have no surrogate to carry; every per-arm
scheme has to special-case them. Their alternatives are both bad: an unranked
plate of 96 proposals set against acquisition-selected ones is not a floor for
*"did anything transfer"* but for *"did anything transfer **and** was anything
screened"*, and criterion 1 is measured against `plain-fresh` -- so a special
case would live exactly where a quiet inflation of the headline would live.

**The cost, stated rather than left to be wondered about.** A surrogate fitted on
random data is weaker than one fitted on a policy's own trajectories: it
discriminates less, so every arm's plate is noisier and the effect the probe is
trying to detect is smaller. That makes the criteria **harder** to pass, which is
the correct direction for a claim intended to survive review. The weak screener
is a choice, not an oversight.

One further consequence has to be read alongside the results: every arm at B is
screened, **including the classical baselines and `random`**, which is not what
any of their papers do -- a bare genetic algorithm has no screen. The arms at B
are therefore proposal distributions under a common screen and are *not* the
published pipelines [evogfn.benchmark.methods][]'s ``BASELINES`` reports. **No
ranking of published methods may be read off this probe.** Their state at A is
still built by their own bare pipelines, which is what makes the carried state
theirs.

Every record stores `surrogate_dataset` and a digest of the measurements the
model was fitted on, so the choice is checkable from the store rather than only
readable in this docstring.

## Deviation 2: both anchors are reached by a legal walk

The specification draws both anchors from the landscape's feasible-sequence
constructor at two controlled Hamming distances. That is infeasible at distance
4: [feasible_sequence][evogfn.landscapes.ehrlich.EhrlichLandscape.feasible_sequence]
takes a seed and walks the Markov chain from a uniform start, with no way to
condition on distance, and two independent draws at $L = 32$, $V = 20$ agree at
about $L / V = 1.6$ positions in expectation. Reaching distance 4 by seed search
is not slow, it is impossible.

So B is built by a walk through the environment's own masks from A -- see
`anchor_pair` -- at **both** levels rather than at the near one only. Drawing the
far anchor from the constructor and the near one from a walk would make the two
levels differ in *how B was drawn* as well as in *how far it is*, and criterion 2
is precisely a comparison between the levels. Equalising the sampling scheme is
what keeps that comparison about distance.

What the walk buys beyond feasibility is stated in `anchor_pair`'s
post-conditions: every intermediate is legal, so B is not merely feasible but
**constructible** from A, which the near level's own rationale asks for.

## Deviation 3: the training campaign does not re-anchor

The diagnostic protocol this landscape is normally run under re-anchors between
rounds. The A campaign here does not. Under re-anchoring the policy would end its
training somewhere the campaign chose, not at A, and the displacement to B --
which is the probe's independent variable and the whole content of criterion 2 --
would be an uncontrolled quantity nobody measured. A fixed anchor is what makes
"trained at A, moved distance $d$ to B" a true description of the run.

## Deviation 4: `plain-retrained` spends no oracle budget at B

The specification says "trained at B from scratch at the same step budget", which
fixes the gradient steps and says nothing about assays. A full campaign at B
would spend 384 oracle calls where every other arm spends 96, **and** its
surrogate would then have seen data near B -- contradicting the specification's
own surrogate-freezing threat. So the arm gets `RETRAIN_STEPS` gradient steps at
B against the *carried* surrogate and then one frozen plate, which holds the
oracle budget and the screening model identical across all ten arms and isolates
exactly one variable: which anchor the policy was trained at.

## Deviation 5: the capacity control carries 237 parameters too many

At this sizing a plain policy has $h^2 + 1668h + 1283$ parameters and an
anchor-conditioned one $h^2 + 2724h + 1283$; at $h = 64$ that is 112,131 and
179,715. Solving for the plain width that matches gives $h \approx 100.87$, and
the discriminant $1668^2 + 4 \cdot 178432 = 3{,}495{,}952$ lies strictly between
$1869^2$ and $1870^2$, so **no integer width matches exactly**.
`CAPACITY_HIDDEN_DIM` is 101, at 179,952 parameters -- 237 more than the arm it
controls for. The direction is the safe one: criterion 3 is tested against a
strictly better-resourced control, so conditioning winning excludes capacity *a
fortiori*. Reporting must say "+237 parameters", never "parameter-matched", and
must add the part matching a count cannot fix: the conditioned policy has a
64-wide trunk fed by a 2,080-wide input and the control a 101-wide trunk fed by a
1,024-wide input, so the two are equal in parameters and unequal in
representation width, and no single plain policy can be equal in both.

## The hazard that fails silently

`AnchorConditionedPolicy._anchor` is registered with ``persistent=True``, so it
is **in the state dict**. Any implementation of "carry the weights" written as
``load_state_dict`` therefore restores anchor A over anchor B, in silence: the
conditioning is simply wrong, the loss stays finite, and the only symptom is a
worse number. The policy object is also shared rather than copied, and
[GFlowNetSampler][evogfn.algorithms.gflownet.sampler.GFlowNetSampler]'s own
docstring states the consequence -- a policy shared between two samplers at
different anchors belongs to the one constructed last. This module holds an
A-context and a B-context in one process by design, so both hazards are live.

`assert_anchor_bound` is called at the top of every frozen proposal and
**raises**; it is not an ``assert``, which ``-O`` removes, and this is the one
condition whose violation produces publishable-looking numbers. Beyond that,
every stored record carries the achieved anchor distance and -- for the
conditioned arms -- the distance the *policy's own buffer* sat at, so a run that
went stale reports zero where it should report the move, and the failure is
visible in the store without re-running anything.
"""

