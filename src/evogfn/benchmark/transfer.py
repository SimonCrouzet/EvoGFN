@dataclass(frozen=True, slots=True)
class ArmAtAnchor:
    """One arm, reduced to the only thing that varies at B: how it proposes.

    Attributes:
        name: The specification's own name for the arm.
        propose: Generates candidates at B. Everything downstream of it -- the
            screen, the rule, the selector, the plate -- is identical across
            arms by construction, which is what deviation 1 buys and what makes
            a difference between arms attributable to the proposer alone.
        parameters: What this arm resolved to, for the record. Provenance only.
        policy: The policy behind the proposal, where there is one, so a caller
            can read its anchor and its weights after the round.
        sampler: The classical sampler behind the proposal, where there is one --
            **the moved one**, the object `propose` actually draws from, not the
            one that stood at A. Held because
            `RunRecord.fitted` is state
            on the sampler and is not derivable from anything the round returns:
            a `mlde-carried` arm that never fitted at A carries nothing to B and
            is random mutagenesis there, while charging the same assays, filling
            the same plate and reporting a best value in the same range as one
            that transferred badly. See
            [MLDE.is_fitted][evogfn.algorithms.baselines.mlde.MLDE.is_fitted].
    """

    name: str
    propose: Callable[[int], Tokens]
    parameters: dict[str, ArmParameter]
    policy: SequencePolicy | None = None
    sampler: Sampler | None = None


def _frozen_arm(
    env: MutationEnvironment, policy: SequencePolicy, *, seed: int
) -> Callable[[int], Tokens]:
    """Bind the anchor once, then hand back a closure that only samples.

    **The anchor is moved here and not inside the closure**, and the ordering is
    load-bearing twice over.

    *It is what lets the frozen check mean anything.* On an
    [AnchorConditionedPolicy][evogfn.models.policy.AnchorConditionedPolicy] the
    anchor is a **persistent buffer**, so it is in the state dict and moving it
    changes [state_digest][evogfn.benchmark.transfer.state_digest]. A closure
    that re-bound on every call would change the digest across its own first
    proposal, and the caller's before/after comparison -- the check that catches
    an optimiser step -- would have to be weakened to tolerate it. Binding
    outside the measured window keeps the digest strict: across a proposal
    *nothing* may move, weights or anchor.

    *It is what keeps the guard live.* Re-binding immediately before each
    rollout would satisfy
    [assert_anchor_bound][evogfn.benchmark.transfer.assert_anchor_bound] by
    construction and the check would never be able to fire. Binding once and
    checking at every proposal is what catches the real hazard: the policy object
    is shared, so anything that builds a sampler at another anchor in between --
    or restores a state dict, which carries anchor A back with it -- steals it,
    and the next proposal raises instead of quietly conditioning on the wrong
    parent.

    Args:
        env: The graph at B. Its parent is what the policy is bound to.
        policy: The policy to propose from. Its anchor is moved; no weight is.
        seed: Seeds the rollout's own stream, separately from anything at A.

    Returns:
        A callable taking a count and returning that many designs.
    """
    if isinstance(policy, AnchorConditionedPolicy):
        policy.set_anchor(env.parent)
    generator = torch.Generator().manual_seed(seed)

    def propose(n: int) -> Tokens:
        return propose_frozen(env, policy, n, generator=generator)

    return propose


def _sampler_arm(sampler: Sampler) -> Callable[[int], Tokens]:
    """A proposal closure over a classical sampler already moved to B.

    Args:
        sampler: The re-anchored sampler.

    Returns:
        A callable taking a count and returning that many designs.
    """

    def propose(n: int) -> Tokens:
        return np.asarray(sampler.propose(n))

    return propose


def _reanchored(sampler: Sampler, env: MutationEnvironment) -> Sampler:
    """Move a classical sampler to B through its own hook.

    Args:
        sampler: The sampler as it stood at A.
        env: The graph at B.

    Returns:
        The moved sampler.

    Raises:
        TypeError: If the sampler cannot re-anchor. Every baseline the probe runs
            can, and one that could not would have to be rebuilt -- which is a
            different arm, not a fallback.
    """
    moved = getattr(sampler, "reanchored", None)
    if moved is None:
        raise TypeError(
            f"{type(sampler).__name__} does not implement reanchored(env), so it cannot be "
            f"moved to the new anchor; rebuilding it instead would be a different arm"
        )
    return cast_sampler(moved(env))


def cast_sampler(value: object) -> Sampler:
    """Narrow a dynamically resolved ``reanchored`` result to a sampler.

    A one-line helper rather than an inline ``cast`` so the narrowing has a place
    to be explained: `_reanchored` resolves the hook by attribute because the
    four baselines do not share a base class that declares it, and the type
    checker cannot see through that.

    Args:
        value: Whatever the hook returned.

    Returns:
        The same object, typed.
    """
    from evogfn.algorithms.base import Sampler as _Sampler  # noqa: PLC0415 - runtime narrowing

    if not isinstance(value, _Sampler):
        raise TypeError(f"reanchored returned a {type(value).__name__}, not a Sampler")
    return value


def arms_at_anchor(
    landscape: EhrlichLandscape,
    prep: SeedPreparation,
    pair: AnchorPair,
    surrogate: FrozenSurrogate,
    budget: ProbeBudget | None = None,
) -> dict[str, ArmAtAnchor]:
    """Build every arm at the moved anchor, ready to propose.

    Nothing here trains except `plain-retrained`, which is the arm whose whole
    definition is that it does -- and even that one spends no oracle budget at B
    and trains against the same shared surrogate every arm screens with, so the
    only variable it moves is which anchor its policy was trained at.

    Args:
        landscape: The instance.
        prep: What this seed's campaigns at A produced.
        pair: The anchors, and the distance between them.
        surrogate: The shared screen, already frozen. Handed in rather than built
            here so that one wrapper serves every arm and "the same model" is an
            object identity rather than a claim.
        budget: Sizes, or ``None`` for the probe as specified.

    Returns:
        The arms by name, in `ARM_NAMES` order.
    """
    sizes = budget or ProbeBudget()
    env = training_environment(landscape, pair.moved)
    # A stream that depends on the anchor as well as the seed, so the near and
    # far levels do not draw the same trajectories from the same weights.
    stream = int(
        np.random.SeedSequence(
            [prep.seed, LEVELS.index(pair.level), pair.achieved_distance]
        ).generate_state(1)[0]
    )
    common: dict[str, ArmParameter] = {
        "level": pair.level,
        "nominal_distance": float(pair.nominal_distance),
        "achieved_distance": float(pair.achieved_distance),
        "configuration": TRANSFER_CONFIGURATION,
        # Which dataset screened this plate, and a hash of it. On every record so
        # that deviation 1 is checkable from the store rather than only readable
        # in a docstring: every arm of one seed must name this dataset and carry
        # this digest, and a row that does not was screened by a different model.
        "surrogate_dataset": prep.surrogate.dataset,
        "surrogate_dataset_digest": prep.surrogate.digest,
        "surrogate_dataset_assays": float(prep.surrogate.oracle_calls),
        "oracle_calls_at_a": float(prep.oracle_calls_at_a),
    }

    def policy_arm(  # noqa: PLR0913 - an arm is defined by what it records
        name: str,
        trained: SequencePolicy,
        *,
        hidden_dim: int,
        anchor_conditioned: bool,
        gradient_steps_at_b: int = 0,
        extra: dict[str, ArmParameter] | None = None,
    ) -> ArmAtAnchor:
        return ArmAtAnchor(
            name=name,
            propose=_frozen_arm(env, trained, seed=stream),
            parameters={
                **common,
                "family": "gflownet",
                "hidden_dim": float(hidden_dim),
                "anchor_conditioned": anchor_conditioned,
                "frozen": gradient_steps_at_b == 0,
                "gradient_steps_at_b": float(gradient_steps_at_b),
                **(extra or {}),
            },
            policy=trained,
        )

    def classical_arm(name: str, sampler: Sampler) -> ArmAtAnchor:
        # Moved once and kept, rather than moved inline into the closure: the
        # object the arm proposes from is the object whose `is_fitted` the record
        # has to carry, and a second `_reanchored` call for the record would
        # produce a *different* copy -- one that never proposed anything.
        moved = _reanchored(sampler, env)
        return ArmAtAnchor(
            name=name,
            propose=_sampler_arm(moved),
            parameters={
                **common,
                "family": "classical",
                "sampler": type(sampler).__name__,
                "frozen": True,
                "gradient_steps_at_b": 0.0,
            },
            sampler=moved,
        )

    fresh = _policy(env, hidden_dim=TRANSFER_HIDDEN_DIM, seed=stream, anchor_conditioned=False)
    retrained = _retrained_at_anchor(
        landscape, env, surrogate, seed=stream, steps=sizes.retraining_steps
    )

    built = [
        policy_arm(
            "plain-transferred",
            prep.plain.policy,
            hidden_dim=TRANSFER_HIDDEN_DIM,
            anchor_conditioned=False,
        ),
        policy_arm(
            "conditioned-transferred",
            prep.conditioned.policy,
            hidden_dim=TRANSFER_HIDDEN_DIM,
            anchor_conditioned=True,
        ),
        policy_arm(
            "plain-wide-transferred",
            prep.plain_wide.policy,
            hidden_dim=CAPACITY_HIDDEN_DIM,
            anchor_conditioned=False,
            # Stored on the arm it belongs to, so a report cannot describe the
            # capacity control as parameter-matched without contradicting its own
            # record. It over-resources the control, which is the safe direction.
            extra={"capacity_residual_parameters": float(CAPACITY_RESIDUAL)},
        ),
        policy_arm("plain-fresh", fresh, hidden_dim=TRANSFER_HIDDEN_DIM, anchor_conditioned=False),
        policy_arm(
            "plain-retrained",
            retrained,
            hidden_dim=TRANSFER_HIDDEN_DIM,
            anchor_conditioned=False,
            gradient_steps_at_b=sizes.retraining_steps,
        ),
        classical_arm("random", RandomMutagenesis(env, seed=stream)),
        classical_arm("genetic-reprojected", prep.genetic_reprojected),
        classical_arm("genetic-rebuilt", prep.genetic_rebuilt),
        classical_arm("cmaes-carried", prep.cmaes),
        classical_arm("mlde-carried", prep.mlde),
    ]
    return {arm.name: arm for arm in built}


def _retrained_at_anchor(
    landscape: EhrlichLandscape,
    env: MutationEnvironment,
    surrogate: FrozenSurrogate,
    *,
    seed: int,
    steps: int = RETRAIN_STEPS,
) -> SequencePolicy:
    """Train a fresh policy at B against the carried surrogate, spending no assays.

    The ceiling arm. See deviation 4 in the module docstring for why it gets
    `RETRAIN_STEPS` against the frozen model rather than a campaign of its own:
    a campaign would spend 384 oracle calls at B where every other arm spends 96,
    and its surrogate would then have seen data near B -- which is exactly the
    confound the specification's own threat list names.

    Args:
        landscape: The instance, read only for its shape.
        env: The graph at B.
        surrogate: The carried model. It is wrapped, so a training routine that
            tried to refit it would raise rather than quietly succeed.
        seed: Seeds the policy and the training.
        steps: Gradient steps.

    Returns:
        The trained policy, which the caller then proposes from frozen.
    """
    proxy = ProxyLandscape(
        surrogate, alphabet=env.alphabet, sequence_length=landscape.sequence_length
    )
    policy = _policy(env, hidden_dim=TRANSFER_HIDDEN_DIM, seed=seed, anchor_conditioned=False)
    train_trajectory_balance(
        env,
        policy,
        proxy,
        TemperedReward(beta=TRANSFER_BETA),
        TrainingConfig(steps=steps, batch_size=TRAINING_BATCH, seed=seed),
        objective=SubTrajectoryBalance(lam=TRANSFER_LAMBDA),
    )
    return policy


