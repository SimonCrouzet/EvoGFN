class StaleAnchorError(ValueError):
    """A policy was asked to propose while conditioned on the wrong parent.

    Its own class rather than a bare ``ValueError`` because it is the one failure
    in this module that a caller might reasonably want to catch and report
    separately: every other error here is a configuration mistake that should
    stop the run, and this one is evidence about the run.
    """


def assert_anchor_bound(policy: SequencePolicy, env: MutationEnvironment) -> None:
    """Refuse to propose from a policy conditioned on a different parent.

    **Raises rather than asserts.** ``python -O`` removes an ``assert``, and this
    is the one condition in the probe whose violation produces numbers that look
    publishable: a stale anchor leaves the conditioning simply wrong while the
    loss stays finite and every downstream metric stays well-formed.

    An unconditioned policy holds no anchor and is left alone, which is what
    keeps this a check on the conditioned arm rather than a constraint on every
    arm that has a policy.

    Args:
        policy: The policy about to propose.
        env: The graph it is about to walk.

    Raises:
        StaleAnchorError: If the policy's anchor is not the environment's parent.
    """
    if not isinstance(policy, AnchorConditionedPolicy):
        return
    held = policy.anchor.detach().cpu().numpy()
    want = np.asarray(env.parent)
    if held.shape != want.shape:
        raise StaleAnchorError(
            f"policy is conditioned on a parent of length {held.shape} and the environment's "
            f"is {want.shape}; these are not the same space"
        )
    if not np.array_equal(held, want):
        raise StaleAnchorError(
            f"policy is conditioned on a parent {int((held != want).sum())} substitutions from "
            f"the environment's; the conditioning would be wrong and the loss would look fine"
        )


def state_digest(policy: nn.Module) -> str:
    """A hash over every tensor in a module's state dict.

    This is how "frozen" is checked. Comparing the digest either side of a
    proposal catches an optimiser step, a mutated anchor buffer and a moved
    ``log_z`` in one comparison, and it does so without anyone having to know
    which parameters exist -- which is the failure a hand-written per-parameter
    check has, since the parameter it forgets is the one that moved.

    The buffer is included deliberately. On an
    [AnchorConditionedPolicy][evogfn.models.policy.AnchorConditionedPolicy] the
    anchor is a persistent buffer, so a digest that skipped buffers would call a
    policy frozen while its conditioning moved underneath it.

    Args:
        policy: Any module.

    Returns:
        A short hex digest, stable across processes and machines.
    """
    digest = hashlib.sha256()
    for name, tensor in sorted(policy.state_dict().items()):
        digest.update(name.encode())
        digest.update(str(tuple(tensor.shape)).encode())
        digest.update(tensor.detach().cpu().contiguous().numpy().tobytes())
    return digest.hexdigest()[:_DIGEST_CHARS]


def propose_frozen(
    env: MutationEnvironment,
    policy: SequencePolicy,
    n: int,
    *,
    generator: torch.Generator,
    epsilon: float = 0.0,
) -> Tokens:
    """Sample ``n`` designs from a policy without training it.

    **Why this cannot be
    [GFlowNetSampler.propose][evogfn.algorithms.gflownet.sampler.GFlowNetSampler.propose].**
    That method's first statement is ``if self._proxy.is_ready: train_...(...)``,
    and the surrogate carried from A *is* ready, so every call to it at B would
    run `TRANSFER_STEPS` gradient steps before sampling. ``reanchored()`` carries
    the policy correctly and does not change this. There is no path in the
    package that proposes from a trained policy without training it, which is why
    this function exists.

    ``epsilon`` defaults to zero, matching that method. A non-zero value would
    inject uniform-over-legal exploration, which flatters an *untrained* policy
    specifically -- and the untrained policy is `plain-fresh`, the floor
    criterion 1 is measured against.

    Args:
        env: The graph to walk. Its masks are the only definition of legal used.
        policy: The policy to sample under. Not modified.
        n: How many designs to return.
        generator: The random stream. Advanced by the call, so two consecutive
            calls return different batches -- frozen is not the same as inert.
        epsilon: Probability of choosing uniformly among legal actions.

    Returns:
        An ``(n, sequence_length)`` array of terminal states.

    Raises:
        StaleAnchorError: If the policy is conditioned on a parent that is not
            this environment's.
    """
    assert_anchor_bound(policy, env)
    with torch.no_grad():
        trajectories = sample_trajectories(env, policy, n, epsilon=epsilon, generator=generator)
    return np.asarray(trajectories.terminal)


