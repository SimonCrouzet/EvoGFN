class FrozenSurrogate(Surrogate):
    """A surrogate that will predict and will not be refitted.

    The carried surrogate has seen no data near B, and freezing it is what
    isolates the policy: refitting would confound transfer of the policy with
    transfer of the surrogate. So this refuses `fit` outright rather than
    documenting that nobody should call it.

    It is a wrapper rather than a flag on
    [DeepEnsemble][evogfn.surrogate.ensemble.DeepEnsemble] because the ensemble
    is in the stored dependency closure and a flag on it would make every record
    in the store stale.

    Args:
        inner: The fitted surrogate to serve predictions from.

    Raises:
        ValueError: If the surrogate has not been fitted. An unfitted surrogate
            that can never be fitted is a screen that will never rank anything,
            and the plate would silently fall back to the first 96 proposals.
    """

    def __init__(self, inner: Surrogate) -> None:
        """Wrap a fitted surrogate."""
        if not inner.is_fitted:
            raise ValueError(
                "the carried surrogate has not been fitted; freezing an unfitted model would "
                "leave every arm's plate unranked and nothing in the record would say so"
            )
        self._inner = inner
        self._predictions = 0
        self._refits_attempted = 0

    @property
    def inner(self) -> Surrogate:
        """The wrapped surrogate, for identity checks."""
        return self._inner

    @property
    def is_fitted(self) -> bool:
        """Always true: this wrapper only ever wraps a fitted model."""
        return True

    @property
    def predictions(self) -> int:
        """How many batches this has scored."""
        return self._predictions

    @property
    def refits_attempted(self) -> int:
        """How many times something tried to refit. Never above zero in a run.

        Incremented before the raise, so a caller that catches the error still
        finds the attempt recorded rather than inferring it from a traceback.
        """
        return self._refits_attempted

    def fit(self, sequences: Tokens, values: Fitness) -> None:  # noqa: ARG002 - it refuses
        """Refuse. Nothing at anchor B trains, and that includes the model.

        Args:
            sequences: Ignored.
            values: Ignored.

        Raises:
            RuntimeError: Always.
        """
        self._refits_attempted += 1
        raise RuntimeError(
            f"the carried surrogate must not be refitted at the moved anchor: it is what "
            f"holds screening constant across arms, and a refit on {np.asarray(sequences).shape[0]}"
            f" designs would confound policy transfer with surrogate transfer"
        )

    def predict(
        self, sequences: Tokens
    ) -> tuple[npt.NDArray[np.floating], npt.NDArray[np.floating]]:
        """Score a batch through the wrapped surrogate.

        Args:
            sequences: An ``(n, length)`` array to score.

        Returns:
            Means and standard deviations, exactly as the wrapped model returns
            them.
        """
        self._predictions += 1
        return self._inner.predict(sequences)

    def __repr__(self) -> str:
        """Name the wrapped surrogate and mark it frozen."""
        return f"FrozenSurrogate({self._inner!r})"


def surrogate_digest(surrogate: Surrogate, probes: Tokens) -> str:
    """A hash of what a surrogate predicts on a fixed probe set.

    Stored on every record so the shared-surrogate ruling is checkable **from the
    store** rather than only from a test that ran once: the ten arms of one
    ``(seed, level)`` must all carry the identical digest, and a refit anywhere
    between them would move it. It uses the public interface only, so it stays
    valid if the ensemble's internals change.

    Args:
        surrogate: The model to probe.
        probes: An ``(m, length)`` array to score. The anchors are what the probe
            uses -- a refit near either would move the prediction there first.

    Returns:
        A short hex digest.
    """
    mean, spread = surrogate.predict(probes)
    digest = hashlib.sha256()
    digest.update(np.asarray(mean, dtype=np.float64).tobytes())
    digest.update(np.asarray(spread, dtype=np.float64).tobytes())
    return digest.hexdigest()[:_DIGEST_CHARS]


@dataclass(frozen=True, slots=True)
class RoundAtAnchor:
    """One measured plate at the moved anchor.

    Attributes:
        batch: The ``(batch_size, length)`` designs measured.
        values: Their ``(batch_size, 1)`` oracle values.
        best: Best value in the plate.
        diversity: Mean pairwise Hamming distance over the plate -- of the
            measured designs, not of the pool. A pool's diversity is a property
            of the proposal distribution; a plate's is what the lab receives.
        feasible_fraction: Share of the plate that is feasible.
        proposed: Designs the arm generated.
        screened: Designs that reached the selector.
        surrogate_predictions: Batches this screen has scored.
        surrogate_refits: Refits attempted. Zero, always; a run that finds
            otherwise has already raised.
    """

    batch: Tokens
    values: Fitness
    best: float
    diversity: float
    feasible_fraction: float
    proposed: int
    screened: int
    surrogate_predictions: int
    surrogate_refits: int


def measure_round(  # noqa: PLR0913 - the round is defined by what it is handed
    landscape: FitnessLandscape,
    pool: Tokens,
    surrogate: FrozenSurrogate,
    *,
    batch_size: int = PLATE,
    best_observed: float = float("-inf"),
    acquisition: Acquisition | None = None,
    selector: BatchSelector | None = None,
) -> RoundAtAnchor:
    """Screen an already-proposed pool with one model, and measure the plate.

    **The pool is passed in rather than proposed here**, and that is what makes
    the two readings comparable rather than merely paired. An arm proposes once at
    B; both screens select from the identical 2,048 designs, so a difference
    between the readings is a difference in *selection* and cannot be a difference
    in what happened to be sampled.

    **Why [Campaign][evogfn.loop.campaign.Campaign] cannot be used for this.**
    ``Campaign._design`` returns ``pool[:size]`` unscored when ``index == 0``.
    A one-round campaign therefore never refits -- which is what the probe wants
    -- and also **never scores the pool**, so the carried surrogate would be
    silently discarded and the arm's whole point with it. Nothing in the campaign's
    output would say so.

    So the round is written out: predict, score, select, evaluate. The defaults
    are [Greedy][evogfn.acquisition.rules.Greedy] and
    [TopK][evogfn.acquisition.rules.TopK], matching ``methods._campaign``, so
    the screening at B is the screening every arm in the suite already gets.

    Args:
        landscape: The oracle. Charged exactly ``batch_size`` calls.
        pool: The ``(n, length)`` candidates this arm proposed.
        surrogate: The screen. Only `predict` is ever called on it, and the
            wrapper refuses anything else.
        batch_size: Designs measured.
        best_observed: Best value in the dataset this screen was fitted on, for
            an improvement-based rule. Ignored by the greedy default, and passed
            anyway so that changing the rule does not silently change what the
            incumbent is.
        acquisition: How prediction and spread become one score.
        selector: How scores become the plate.

    Returns:
        The plate and what it cost.

    Raises:
        ValueError: If the pool is smaller than the plate, which would leave the
            selector nothing to select from.
    """
    pool = np.asarray(pool)
    if pool.shape[0] < batch_size:
        raise ValueError(
            f"the pool holds {pool.shape[0]} designs and the plate takes {batch_size}; there "
            f"would be nothing to screen"
        )
    rule = acquisition or Greedy()
    picker = selector or TopK()

    mean, spread = surrogate.predict(pool)
    scores = rule.score(mean, spread, best_observed=best_observed)
    batch = pool[picker.select(pool, scores, batch_size)]
    values = landscape.evaluate(batch)

    finite = np.asarray(values, dtype=np.float64)[np.isfinite(values)]
    return RoundAtAnchor(
        batch=batch,
        values=values,
        # An all-infeasible plate has no best value to report. Reporting -inf is
        # the honest answer and is what the regret against it will say.
        best=float(finite.max()) if finite.size else float("-inf"),
        diversity=diversity(batch),
        feasible_fraction=float(np.asarray(landscape.is_feasible(batch)).mean()),
        proposed=int(pool.shape[0]),
        screened=int(pool.shape[0]),
        surrogate_predictions=surrogate.predictions,
        surrogate_refits=surrogate.refits_attempted,
    )


