def diagnostic_landscape() -> EhrlichLandscape:
    """The instance the probe runs on: L=32, v=20, c=2, k=4, density 0.5, seed 7.

    Built from [DIAGNOSTIC_INSTANCE][evogfn.benchmark.suite.DIAGNOSTIC_INSTANCE]
    rather than restated, so the probe provably runs the same instance the
    configuration was selected on and no re-selection is required.

    Returns:
        The landscape.
    """
    return EhrlichLandscape(**DIAGNOSTIC_INSTANCE)  # type: ignore[arg-type]


def task_name(level: str) -> str:
    """The store key one level's records live under.

    Args:
        level: ``"near"`` or ``"far"``.

    Returns:
        The task name.
    """
    return f"{TASK_PREFIX}-{level}"


def _protocol_repr(pair: AnchorPair, attainable: AttainableOptimum) -> str:
    """Provenance for a stored record: what was run and what it was scored against.

    Written into ``RunRecord.protocol``, which is the field every table reads to
    decide whether two rows are comparable. It carries the tier as well as the
    numbers: these rows are `Purpose.DIAGNOSTIC` and must never be promoted into
    a method ranking, since the probe runs one instance of one landscape.

    Args:
        pair: The anchors.
        attainable: What B's search space was audited to contain.

    Returns:
        One line.
    """
    protocol = Protocol(
        rounds=1, batch_size=PLATE, max_mutations=DIAGNOSTIC_MUTATIONS, label="one frozen plate"
    )
    return (
        f"{task_name(pair.level)} ({protocol!r}, {DIAGNOSTIC_MUTATIONS}/round, "
        f"anchor moved {pair.achieved_distance} of a nominal {pair.nominal_distance}, "
        f"{Purpose.DIAGNOSTIC}, instance {DIAGNOSTIC_INSTANCE}, attainable {attainable!r})"
    )


def run_transfer_probe(  # noqa: PLR0913 - a study is defined by what it runs over
    store: ResultStore,
    seeds: Sequence[int],
    *,
    levels: Sequence[Literal["near", "far"]] = LEVELS,
    landscape: EhrlichLandscape | None = None,
    budget: ProbeBudget | None = None,
    report: Callable[[str], None] = print,
) -> int:
    """Run whatever the store is missing, writing each arm's plate as it lands.

    The loop is seed-outermost and level-inner, which is not cosmetic: anchor A
    does not depend on the level, so one seed's eight campaigns at A serve both
    distances, and that is the factor of two the specification's cost section was
    reaching for. It also means a seed is skipped only when **every** arm at
    **every** level already holds a current record -- a partially cached seed
    still pays for A, because there is no way to reconstruct a trained policy
    from a stored number.

    Args:
        store: Where results go, and what says which are already held.
        seeds: Seeds wanted.
        levels: Distance levels to run.
        landscape: The instance, or ``None`` for `diagnostic_landscape`.
        budget: Sizes, or ``None`` for the probe as specified.
        report: Where progress lines go.

    Returns:
        How many arm-rounds were actually measured.
    """
    instance = diagnostic_landscape() if landscape is None else landscape
    sizes = budget or ProbeBudget()
    ran = 0
    for seed in seeds:
        wanted = {
            level: [name for name in ARM_NAMES if store.missing(task_name(level), name, [seed])]
            for level in levels
        }
        if not any(wanted.values()):
            report(f"  seed {seed}: cached at every level")
            continue

        started = time.perf_counter()
        prep = prepare_seed(instance, seed, sizes)
        report(f"  seed {seed}: campaigns at anchor A in {time.perf_counter() - started:.0f}s")

        for level in levels:
            if not wanted[level]:
                continue
            ran += _run_level(
                store,
                instance,
                prep,
                level=level,
                arms=wanted[level],
                budget=sizes,
                report=report,
            )
    return ran


def _run_level(  # noqa: PLR0913 - one argument per thing a level is
    store: ResultStore,
    landscape: EhrlichLandscape,
    prep: SeedPreparation,
    *,
    level: Literal["near", "far"],
    arms: Sequence[str],
    budget: ProbeBudget,
    report: Callable[[str], None],
) -> int:
    """Measure one plate per outstanding arm at one level, and store each.

    Args:
        store: Where results go.
        landscape: The instance.
        prep: What this seed's campaigns at A produced.
        level: Which distance.
        arms: Arm names still missing for this seed.
        budget: Sizes.
        report: Where progress lines go.

    Returns:
        How many arm-rounds were measured.

    Raises:
        RuntimeError: If a frozen proposal moved any weight. Raised rather than
            recorded: a probe whose "frozen" arm trained has measured something
            other than transfer, and storing that number would put it in a table
            nothing downstream could tell apart from a real one.
    """
    pair = anchor_pair(
        landscape,
        seed=prep.seed,
        level=level,
        near_distance=budget.near_distance,
        far_distance=budget.far_distance,
    )
    attainable = anchor_attainable(
        landscape,
        pair.moved,
        budget=DIAGNOSTIC_MUTATIONS,
        label=f"{task_name(level)}/seed{prep.seed}",
        beam_width=budget.beam_width,
    )
    # One wrapper for every arm, so "the same surrogate" is an object identity
    # rather than a claim, and so its prediction count totals across the level.
    frozen = FrozenSurrogate(prep.surrogate.surrogate)
    probes = np.stack([np.asarray(pair.training), np.asarray(pair.moved)])
    digest = surrogate_digest(frozen, probes)
    built = arms_at_anchor(landscape, prep, pair, frozen, budget)

    ran = 0
    for name in arms:
        arm = built[name]
        cpu_started = time.process_time()
        wall_started = time.perf_counter()
        before = None if arm.policy is None else state_digest(arm.policy)
        pool = np.asarray(arm.propose(budget.pool_size))
        after = None if arm.policy is None else state_digest(arm.policy)
        if before is not None and before != after:
            raise RuntimeError(
                f"{name} at seed {prep.seed}: the policy's weights moved during a proposal that "
                f"was supposed to be frozen; the arm trained where nothing should train"
            )
        round_at_b = measure_round(
            landscape,
            pool,
            frozen,
            batch_size=budget.batch_size,
            best_observed=prep.surrogate.best,
        )
        store.append(
            store.stamp(
                depends_on=TRANSFER_DEPENDENCIES,
                task=task_name(level),
                method=name,
                seed=prep.seed,
                protocol=_protocol_repr(pair, attainable),
                best=round_at_b.best,
                # Against B's own attainable optimum, at its searched lower bound
                # -- the repository's convention, and the only end witnessed by a
                # design something actually constructed. It can come out negative
                # where an arm beats the beam, which is evidence about the audit
                # and not about the arm.
                regret=attainable.lower - round_at_b.best,
                diversity=round_at_b.diversity,
                feasible_fraction=round_at_b.feasible_fraction,
                oracle_calls=int(round_at_b.batch.shape[0]),
                proposals=round_at_b.proposed,
                # Off the moved sampler, not off `frozen` -- which also answers
                # to `is_fitted`, is in scope right here, and is always True.
                # See `arm_fitted`.
                fitted=arm_fitted(arm),
                deterministic=is_deterministic(),
                trace=[round_at_b.best],
                parameters={
                    **arm.parameters,
                    # What the one shared model predicts on the two anchors. Every
                    # arm of this (seed, level) must carry the identical value:
                    # two that do not were screened by different models, whatever
                    # `surrogate_dataset` claims, and that is deviation 1 broken.
                    "surrogate_prediction_digest": digest,
                    "surrogate_refits_at_b": float(round_at_b.surrogate_refits),
                    "attainable_lower": attainable.lower,
                    "attainable_upper": attainable.upper,
                    "solvable_headroom": attainable.solvable_headroom,
                    "attainable_method": attainable.method,
                    "solved_by_arm": attainable.solved_by(round_at_b.best),
                    "policy_state_digest": "" if after is None else after,
                    # The stale-anchor tell. It must equal the achieved distance;
                    # a run whose buffer never moved reports zero here while every
                    # other column looks fine.
                    **_anchor_fields(arm, pair),
                },
                top_sequences=_top_designs(round_at_b),
                cpu_seconds=time.process_time() - cpu_started,
                wall_seconds=time.perf_counter() - wall_started,
            )
        )
        ran += 1
    report(
        f"    {task_name(level)}/seed {prep.seed}: {ran} arms at distance "
        f"{pair.achieved_distance}, attainable {attainable!r}"
    )
    return ran


def arm_fitted(arm: ArmAtAnchor) -> bool | None:
    """Whether this arm's own model had taken over, or ``None`` if it has none.

    Read **off the arm's sampler**, by the same ``getattr(..., "is_fitted",
    None)`` idiom [evogfn.benchmark.suite][]'s ``_sampler_fields`` uses, and
    tri-valued for the same reason: ``None`` is "nothing here fits a model" --
    a genetic algorithm, a frozen policy -- and ``False`` is a measurement, the
    one that says an arm named for a supervised method spent its whole life in
    its random-screening stage. Collapsing the two would accuse every classical
    rung of a failure only one of them can have.

    It matters most for `mlde-carried`, whose premise is that MLDE's state is
    anchor-independent and transfers in full. If MLDE never fitted at A it
    carries nothing to B and the arm *is* random mutagenesis there, at the same
    assay spend, the same plate and a best value in the same range as a
    supervised method that transferred badly.
    [MLDE.is_fitted][evogfn.algorithms.baselines.mlde.MLDE.is_fitted] is the
    only thing separating those two readings, and it lives on the object rather
    than on anything the round returns.

    **Not the surrogate.** [FrozenSurrogate][evogfn.benchmark.transfer.FrozenSurrogate]
    also carries an ``is_fitted``, it is in scope at the call site, and it is
    hard-coded ``True`` -- it refuses to wrap an unfitted model. Reading it here
    would stamp ``True`` on all ten arms, including the ones that fit nothing,
    and the column would look populated while saying nothing about any sampler.

    Args:
        arm: The arm just measured. Its ``sampler`` is the moved object the
            proposals actually came from.

    Returns:
        The sampler's fit state, or ``None`` where there is no sampler or it
        carries no such notion.
    """
    fitted = getattr(arm.sampler, "is_fitted", None)
    return None if fitted is None else bool(fitted)


def _anchor_fields(arm: ArmAtAnchor, pair: AnchorPair) -> dict[str, ArmParameter]:
    """How far the policy's own anchor buffer sat from the training anchor.

    Recorded only for an arm that has one. An absent key is not a zero, and an
    arm without a conditioned policy has no such distance rather than a distance
    of nothing -- which is the reading `RunRecord.parameters` asks for.

    Args:
        arm: The arm just measured.
        pair: The anchors.

    Returns:
        One entry, or none.
    """
    if not isinstance(arm.policy, AnchorConditionedPolicy):
        return {}
    held = arm.policy.anchor.detach().cpu().numpy()
    return {"policy_anchor_distance": float(np.count_nonzero(held != np.asarray(pair.training)))}


def _top_designs(round_at_b: RoundAtAnchor, k: int = 10) -> list[list[int]]:
    """The best designs in a plate, for inspection.

    Args:
        round_at_b: The measured plate.
        k: How many to keep.

    Returns:
        Token lists, best first.
    """
    values = np.asarray(round_at_b.values, dtype=np.float64).reshape(-1)
    order = np.argsort(-values, kind="stable")[:k]
    return [[int(token) for token in round_at_b.batch[index]] for index in order]
