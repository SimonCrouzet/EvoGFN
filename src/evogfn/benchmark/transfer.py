def anchor_attainable(  # noqa: PLR0913 - the audit's knobs are its definition
    landscape: EhrlichLandscape,
    anchor: Tokens,
    *,
    budget: int,
    label: str,
    beam_width: int | None = None,
    placements: int = DEFAULT_PLACEMENTS,
    patience: int = DEFAULT_PATIENCE,
) -> AttainableOptimum:
    """What one round from ``anchor`` could attain, as the audited quantity.

    Regret must be taken against what B's own search space contains, not against
    A's and not against the landscape's nominal 1.0: attainability depends on the
    anchor, and a regret column taken against an unreachable target carries a
    constant no method could have removed.

    [attainable_optimum][evogfn.benchmark.attainable.attainable_optimum] reads
    ``task.parent(landscape)`` and
    [reanchored_attainable][evogfn.benchmark.attainable.reanchored_attainable]
    chains from the wild type, so neither accepts an arbitrary anchor. This is a
    pure re-parameterisation of the same audited quantity: both private helpers
    it calls take ``parent`` as a plain argument and neither reads a
    [Task][evogfn.benchmark.tasks.Task].

    **Reaching into two private names is deliberate.** The right long-term shape
    is a public ``attainable_at(landscape, parent, budget)`` in
    [evogfn.benchmark.attainable][] -- and adding it today edits a module in the
    stored closure and makes every record in the store stale. There is precedent
    for the reach (``cmaes._permitted_adjacencies`` reads ``env._transitions``,
    with its reasoning written down) and this is the same trade made for the same
    reason.

    Args:
        landscape: The instance.
        anchor: The parent to audit from.
        budget: Mutation budget, which for this probe is one round's.
        label: Name carried on the result, so a bound cannot drift from what it
            describes.
        beam_width: Beam width for the searched lower bound. Defaults as
            `attainable_optimum` does.
        placements: Placements kept per motif when scoring the beam.
        patience: Beam steps without improvement before stopping.

    Returns:
        The attainable optimum, exact where the bracket closed and bounded where
        it did not. Returning
        [AttainableOptimum][evogfn.benchmark.attainable.AttainableOptimum] rather
        than a float is what inherits the interval discipline -- ``lower``
        witnessed, ``upper`` certified, ``exact`` only when pinned -- instead of
        reimplementing it.

    Raises:
        ValueError: If the landscape reports no optimum, or the budget is not
            positive.
    """
    if budget < 1:
        raise ValueError(f"budget must be at least 1, got {budget}")
    optimum = landscape.optimum
    if optimum is None:
        raise ValueError(f"{label}: landscape reports no optimum, so it has no regret to have")
    nominal = float(np.max(optimum))

    env = MutationEnvironment(
        anchor,
        landscape.alphabet,
        max_mutations=min(budget, landscape.sequence_length),
        transitions=np.asarray(landscape.transition_matrix),
    )
    upper, upper_how = attainable_module._certified_upper_bound(landscape, anchor, budget)
    lower, lower_how = attainable_module._searched_lower_bound(
        landscape,
        env,
        anchor,
        budget,
        beam_width=(
            max(MIN_BEAM_WIDTH, DEFAULT_BEAM_CELLS // landscape.sequence_length)
            if beam_width is None
            else beam_width
        ),
        placements=placements,
        patience=patience,
        ceiling=upper,
    )
    pinned = abs(lower - upper) <= _PINNED_TOLERANCE
    return AttainableOptimum(
        task=label,
        budget=budget,
        nominal=nominal,
        lower=lower,
        upper=min(upper, nominal),
        exact=lower if pinned else None,
        method=(
            f"pinned: {lower_how} met {upper_how}"
            if pinned
            else f"bounded: {lower_how} below {upper_how}"
        ),
    )


