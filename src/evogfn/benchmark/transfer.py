@dataclass(frozen=True, slots=True)
class AnchorPair:
    """The two parents one seed of the probe runs between.

    Attributes:
        training: Anchor A, where the policy is trained.
        moved: Anchor B, where every arm is measured.
        level: ``"near"`` or ``"far"``.
        nominal_distance: The distance asked for.
        achieved_distance: The distance obtained. Carried separately and stored
            on every record because the specification's own threat list asks for
            the distribution of achieved distances rather than the nominal ones.
            Under `anchor_pair` the two coincide by construction; the field
            exists so that a change to the construction is visible in the store
            rather than only in the source.
    """

    training: Tokens
    moved: Tokens
    level: Literal["near", "far"]
    nominal_distance: int
    achieved_distance: int


def anchor_pair(  # noqa: PLR0913 - a pair is defined by the distances it states
    landscape: EhrlichLandscape,
    *,
    seed: int,
    level: Literal["near", "far"],
    near_distance: int = NEAR_DISTANCE,
    far_distance: int = FAR_DISTANCE,
    round_budget: int = DIAGNOSTIC_MUTATIONS,
) -> AnchorPair:
    """Anchor A, and an anchor B a controlled number of substitutions away.

    A is
    [feasible_sequence][evogfn.landscapes.ehrlich.EhrlichLandscape.feasible_sequence]
    at this seed -- the same constructor
    [Task.parent][evogfn.benchmark.tasks.Task.parent] uses for every Ehrlich
    task, so A is drawn exactly as a wild type is, and it varies per seed so that
    the probe is paired on the instance as well as on the arms.

    B is reached from A by a **walk through the environment's own masks**, one
    legal substitution at a time, at the level's distance. Nothing about
    reachability is re-derived: every step is drawn from
    [forward_mask][evogfn.env.mutation.MutationEnvironment.forward_mask] and
    applied by [step][evogfn.env.mutation.MutationEnvironment.step]. Each
    position may be mutated at most once in that graph, so a walk of $d$ steps
    lands at distance exactly $d$.

    Both levels are walked, which is a declared deviation -- see the module
    docstring. Drawing one level from the constructor and the other from a walk
    would make the levels differ in sampling scheme as well as in distance, and
    criterion 2 is a comparison *between* the levels.

    Args:
        landscape: The instance. Supplies the alphabet, the transition matrix and
            the feasible-sequence constructor.
        seed: Seeds A and, through a separate stream per level, the walk to B.
        level: Which distance to build.
        near_distance: Substitutions at the near level.
        far_distance: Substitutions at the far level.
        round_budget: One round's mutation budget, used only to check that the
            far anchor really is beyond a single round's reach from A.

    Returns:
        The pair, with the achieved distance recorded.

    Raises:
        ValueError: If a distance is not positive, if it exceeds the sequence
            length, if the walk runs out of legal moves, or if any of the
            post-conditions below fails.
    """
    distance = near_distance if level == "near" else far_distance
    if distance < 1 or distance > landscape.sequence_length:
        raise ValueError(
            f"the {level} distance must lie in [1, {landscape.sequence_length}], got {distance}"
        )

    training = np.asarray(landscape.feasible_sequence(seed))
    # A stream per (seed, level), so the near and far walks are independent and
    # neither is a prefix of the other -- a shared stream would make the near
    # anchor lie on the path to the far one, and the two levels would then differ
    # by less than their distances suggest.
    stream = np.random.default_rng(np.random.SeedSequence([seed, LEVELS.index(level)]))
    walk_env = MutationEnvironment(
        training,
        landscape.alphabet,
        max_mutations=distance,
        transitions=np.asarray(landscape.transition_matrix),
    )
    moved = _legal_walk(walk_env, stream, distance)

    achieved = int(np.count_nonzero(np.asarray(moved) != training))
    _check_anchor(
        landscape,
        training,
        moved,
        level=level,
        distance=distance,
        achieved=achieved,
        walk_env=walk_env,
        round_budget=round_budget,
    )
    return AnchorPair(
        training=training,
        moved=moved,
        level=level,
        nominal_distance=distance,
        achieved_distance=achieved,
    )


def _legal_walk(env: MutationEnvironment, rng: np.random.Generator, steps: int) -> Tokens:
    """Take ``steps`` substitutions drawn uniformly from the legal ones.

    Args:
        env: The graph, anchored where the walk starts.
        rng: The random stream.
        steps: How many substitutions to take.

    Returns:
        The sequence the walk ended on.

    Raises:
        ValueError: If the walk runs out of legal substitutions. On a sparse
            transition matrix that is a real possibility rather than a formality,
            and it is a fact about the anchor rather than a bug -- so it is
            reported as one instead of being silently short.
    """
    state = env.initial(1)
    for taken in range(steps):
        legal = np.nonzero(env.forward_mask(state)[0, : env.n_mutation_actions])[0]
        if legal.size == 0:
            raise ValueError(
                f"the walk ran out of legal substitutions after {taken} of {steps} steps; "
                f"this anchor has no neighbourhood of that radius under the transition matrix"
            )
        state = env.step(state, np.asarray([int(rng.choice(legal))], dtype=np.int64))
    return np.asarray(state.sequences[0]).copy()


def _check_anchor(  # noqa: PLR0913 - one argument per post-condition
    landscape: EhrlichLandscape,
    training: Tokens,
    moved: Tokens,
    *,
    level: str,
    distance: int,
    achieved: int,
    walk_env: MutationEnvironment,
    round_budget: int,
) -> None:
    """Check everything the probe assumes about an anchor pair.

    Each of these is cheap, and each catches something that would otherwise
    surface much later and much less legibly:

    * **B is feasible.** Otherwise
      [reanchored][evogfn.env.mutation.MutationEnvironment.reanchored] refuses
      mid-run, after the training campaign has been paid for.
    * **The distance is the one asked for.** The walk guarantees it; the check is
      what makes a future change to the walk visible.
    * **B is constructible from A within the level's distance.** True by
      construction, and asserted for the same reason.
    * **At the far level, B is beyond one round's reach from A.** This is the
      operative content of "no trajectory from the training anchor arrives in
      this neighbourhood", and it is a property that must be checked rather than
      assumed.

    Args:
        landscape: The instance.
        training: Anchor A.
        moved: Anchor B.
        level: Which level was built.
        distance: The distance asked for.
        achieved: The distance obtained.
        walk_env: The environment the walk ran in, anchored at A at the level's
            radius.
        round_budget: One round's mutation budget.

    Raises:
        ValueError: If any post-condition fails.
    """
    if not bool(landscape.is_feasible(np.asarray(moved)[None, :])[0]):
        raise ValueError(
            f"the {level} anchor is infeasible; no environment could be anchored at it"
        )
    if achieved != distance:
        raise ValueError(
            f"the {level} anchor sits {achieved} substitutions from the training anchor, "
            f"not the {distance} asked for"
        )
    if not bool(walk_env.is_constructible(np.asarray(moved)[None, :])[0]):
        raise ValueError(
            f"the {level} anchor has no legal construction order from the training anchor, "
            f"which the walk was supposed to guarantee"
        )
    if level == "far":
        round_env = MutationEnvironment(
            training,
            landscape.alphabet,
            max_mutations=round_budget,
            transitions=np.asarray(landscape.transition_matrix),
        )
        if bool(round_env.is_reachable(np.asarray(moved)[None, :])[0]):
            raise ValueError(
                f"the far anchor is within {round_budget} substitutions of the training anchor, "
                f"so it is not beyond one round's reach and the two levels do not bracket anything"
            )


