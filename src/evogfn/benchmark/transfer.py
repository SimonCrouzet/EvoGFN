def _policy(
    env: MutationEnvironment,
    *,
    hidden_dim: int,
    seed: int,
    anchor_conditioned: bool,
) -> SequencePolicy:
    """A policy sized to an environment's action space.

    Deliberately a mirror of ``methods._policy`` rather than a call to it: that
    name is private, and its module is in the stored dependency closure, so
    importing it would tie this probe to a name its owner has not published.
    ``tests/benchmark/test_transfer.py`` pins the two against each other, so the
    duplication is checked rather than trusted -- a drift in sizing would make
    the probe's policies a different network from the suite's while both arms
    kept the same name.

    Args:
        env: The environment the policy proposes into. Only its shape is read,
            except for ``anchor_conditioned``, where the anchor is read too -- and
            the anchor moves, so binding it here is never the last word.
        hidden_dim: Width of the trunk.
        seed: Seeds the initialisation.
        anchor_conditioned: Feed the anchor alongside the state.

    Returns:
        The policy, with a flow head, since the configuration under test is a
        sub-trajectory-balance one.
    """
    if anchor_conditioned:
        return AnchorConditionedPolicy(
            anchor=env.parent,
            n_actions=env.n_actions,
            sequence_length=env.sequence_length,
            n_tokens=env.alphabet.size,
            hidden_dim=hidden_dim,
            learn_flow=True,
            seed=seed,
        )
    return SequencePolicy(
        n_actions=env.n_actions,
        sequence_length=env.sequence_length,
        n_tokens=env.alphabet.size,
        hidden_dim=hidden_dim,
        learn_flow=True,
        seed=seed,
    )


def training_environment(landscape: EhrlichLandscape, anchor: Tokens) -> MutationEnvironment:
    """The graph one round searches from an anchor.

    Args:
        landscape: The instance, which supplies the alphabet and the feasibility
            rule. Handing the transition matrix over is what makes masked
            sampling possible at all; omitting it does not raise, it silently
            switches feasibility-by-construction off.
        anchor: The parent.

    Returns:
        A [MutationEnvironment][evogfn.env.mutation.MutationEnvironment] at the
        diagnostic per-round radius.
    """
    return MutationEnvironment(
        anchor,
        landscape.alphabet,
        max_mutations=DIAGNOSTIC_MUTATIONS,
        transitions=np.asarray(landscape.transition_matrix),
    )


@dataclass(frozen=True, slots=True)
class TrainedPolicy:
    """A policy trained at anchor A, and the model it trained against.

    Attributes:
        policy: The trained network. Shared, not copied -- see the module
            docstring's account of what that costs.
        best_at_a: Best value the campaign measured. Provenance only: the
            incumbent an acquisition rule is handed at B comes from the shared
            screen's own dataset, since a screen can only know what it was shown.
        oracle_calls: Assays the campaign spent at A.

    Note:
        The ensemble this campaign fitted and trained against is deliberately
        **not** kept. It is what the shipped method trains against at A -- a
        GFlowNet optimising a proxy over its own measurements is what the method
        *is* -- and it is emphatically not the screen at B: deviation 1 rules
        that no arm's own model may select its own plate, because a model fitted
        on a policy's trajectories judges that policy's proposals
        in-distribution. Dropping it here is what makes that unavailable rather
        than merely discouraged.
    """

    policy: SequencePolicy
    best_at_a: float
    oracle_calls: int


def train_policy_at_anchor(  # noqa: PLR0913 - a campaign is defined by its protocol
    landscape: EhrlichLandscape,
    anchor: Tokens,
    *,
    seed: int,
    hidden_dim: int = TRANSFER_HIDDEN_DIM,
    anchor_conditioned: bool = False,
    steps: int = TRANSFER_STEPS,
    rounds: int = TRANSFER_ROUNDS,
    batch_size: int = PLATE,
) -> TrainedPolicy:
    """Run one training campaign at A and hand back what it left behind.

    The campaign is assembled here rather than through
    [evogfn.benchmark.methods][] for two reasons, and only the second is about
    the fingerprint. The arms have to hand back the *policy* and the *surrogate*,
    and neither is reachable from a
    [Campaign][evogfn.loop.campaign.Campaign] -- ``campaign.sampler`` is a
    sampler and the policy inside it is private. Building the parts here is what
    makes the probe able to move them.

    **The anchor does not move during training.** See deviation 3 in the module
    docstring: under re-anchoring the policy would finish somewhere the campaign
    chose, and the displacement to B -- the probe's independent variable -- would
    be uncontrolled.

    Args:
        landscape: The instance.
        anchor: Anchor A.
        seed: Seeds the policy, the surrogate, the training and the sampling.
        hidden_dim: Width of the trunk.
        anchor_conditioned: Whether the policy is told which parent it is at.
        steps: Gradient steps per round.
        rounds: Rounds the campaign runs.
        batch_size: Designs measured per round.

    Returns:
        The trained policy and the model it trained against.
    """
    env = training_environment(landscape, anchor)
    ensemble = DeepEnsemble(
        n_tokens=landscape.alphabet.size,
        sequence_length=landscape.sequence_length,
        epochs=SURROGATE_EPOCHS,
        seed=seed,
    )
    proxy = ProxyLandscape(ensemble, alphabet=env.alphabet, sequence_length=env.sequence_length)
    policy = _policy(env, hidden_dim=hidden_dim, seed=seed, anchor_conditioned=anchor_conditioned)
    sampler = GFlowNetSampler(
        env,
        policy,
        proxy=proxy,
        reward=TemperedReward(beta=TRANSFER_BETA),
        config=TrainingConfig(steps=steps, batch_size=TRAINING_BATCH, seed=seed),
        objective=SubTrajectoryBalance(lam=TRANSFER_LAMBDA),
        seed=seed,
    )
    campaign = Campaign(
        landscape=landscape,
        sampler=sampler,
        surrogate=ensemble,
        acquisition=Greedy(),
        selector=TopK(),
        rounds=rounds,
        batch_size=batch_size,
        pool_size=TRANSFER_POOL,
        environment=env,
        reanchor=False,
    )
    result = campaign.run()
    return TrainedPolicy(
        policy=policy,
        best_at_a=float(result.best_value),
        oracle_calls=int(result.oracle_calls),
    )


@dataclass(frozen=True, slots=True)
class FittedSurrogate:
    """The model every arm at B screens with, and the data behind it.

    The dataset travels *with* the model rather than being remembered separately,
    so a stored plate cannot be described as neutrally screened while the record
    says otherwise.

    Attributes:
        surrogate: The fitted ensemble.
        best: Best value in the dataset. This is the incumbent an
            improvement-based rule is handed, and it is the best *this dataset*
            saw rather than the best anything at A saw: a screen can only know
            what it was shown.
        oracle_calls: Assays the dataset cost.
        dataset: What it was fitted on -- `INDEPENDENT_DATASET`, always, and a
            field rather than a constant so that a future run under a different
            dataset could never be mistaken for one of these.
        digest: A hash of the measured sequences and values. Stored so that "all
            ten arms of this seed screened under one model" is checkable from the
            store years later rather than only from a test that ran once: two
            records of one seed carrying different digests were screened by
            different models, whatever they claim.
    """

    surrogate: DeepEnsemble
    best: float
    oracle_calls: int
    dataset: str
    digest: str


def _fit_surrogate(  # noqa: PLR0913 - a fitted model is defined by what it saw
    landscape: EhrlichLandscape,
    sequences: Tokens,
    values: Fitness,
    *,
    seed: int,
    dataset: str,
    oracle_calls: int,
) -> FittedSurrogate:
    """Fit an ensemble on a measured dataset and record what it saw.

    Split out from `fit_shared_surrogate` so that the model and its provenance
    are built in one place: a digest computed anywhere but beside the ``fit`` it
    describes is a digest that can drift from the data it claims to identify.

    Args:
        landscape: The instance, read for its shape.
        sequences: The measured designs.
        values: Their measured values.
        seed: Seeds the ensemble.
        dataset: What this dataset is, for the record.
        oracle_calls: Assays it cost, or zero where they were charged elsewhere.

    Returns:
        The fitted model and its provenance.
    """
    designs = np.asarray(sequences)
    measured = np.asarray(values, dtype=np.float64)
    ensemble = DeepEnsemble(
        n_tokens=landscape.alphabet.size,
        sequence_length=landscape.sequence_length,
        epochs=SURROGATE_EPOCHS,
        seed=seed,
    )
    ensemble.fit(designs, measured)

    digest = hashlib.sha256()
    digest.update(designs.astype(np.int64).tobytes())
    digest.update(measured.tobytes())
    finite = measured[np.isfinite(measured)]
    return FittedSurrogate(
        surrogate=ensemble,
        best=float(finite.max()) if finite.size else float("-inf"),
        oracle_calls=oracle_calls,
        dataset=dataset,
        digest=digest.hexdigest()[:_DIGEST_CHARS],
    )


def fit_shared_surrogate(
    landscape: EhrlichLandscape,
    anchor: Tokens,
    *,
    seed: int,
    rounds: int = TRANSFER_ROUNDS,
    batch_size: int = PLATE,
) -> FittedSurrogate:
    """Fit the one screen every arm at B uses, on data no proposer produced.

    Random mutagenesis at anchor A, at exactly the oracle budget a training
    campaign spends, measured by the oracle and fitted once. **No acquisition
    rule is involved and no round feeds the next**, which is what makes the
    dataset independent rather than merely different: a random sampler screened
    by its own surrogate would drift towards whatever that surrogate liked, and
    the dataset would then carry a preference after all.

    See deviation 1 in the module docstring for the three arguments behind this
    -- screening has to be identical, no arm's own model can be neutral, and
    `plain-fresh` would otherwise need a special case sitting under criterion 1 --
    and for the cost: a weaker screen, noisier plates, a smaller detectable
    effect, and criteria that are correspondingly harder to pass.

    Args:
        landscape: The instance.
        anchor: Anchor A.
        seed: Seeds the ensemble's initialisation and the mutagenesis.
        rounds: Plates to draw. Together with ``batch_size`` this is the budget,
            matched to a training campaign's, so the screen is fitted on as much
            data as any arm's own campaign would have produced.
        batch_size: Designs per plate.

    Returns:
        The fitted model and the provenance of what it saw.
    """
    env = training_environment(landscape, anchor)
    # A stream of its own, so the shared dataset is not the opening draw of any
    # arm's random stream -- which would make "generated by no proposer" true of
    # the method and false of the numbers.
    stream = int(np.random.SeedSequence([seed, _REFERENCE_STREAM]).generate_state(1)[0])
    campaign = Campaign(
        landscape=landscape,
        sampler=RandomMutagenesis(env, seed=stream),
        surrogate=None,
        rounds=rounds,
        batch_size=batch_size,
        pool_size=batch_size,
        environment=env,
        reanchor=False,
    )
    result = campaign.run()
    return _fit_surrogate(
        landscape,
        result.sequences,
        result.values,
        seed=seed,
        dataset=INDEPENDENT_DATASET,
        oracle_calls=int(result.oracle_calls),
    )


def run_classical_at_anchor(  # noqa: PLR0913 - a campaign is defined by its protocol
    landscape: EhrlichLandscape,
    anchor: Tokens,
    *,
    build: Callable[[MutationEnvironment, int], Sampler],
    seed: int,
    rounds: int = TRANSFER_ROUNDS,
    batch_size: int = PLATE,
) -> Sampler:
    """Run one classical baseline at A and hand back the state it accumulated.

    **Bare, and pooled at the plate**: that is the pipeline each of these papers
    publishes, and it is what makes the state carried to B genuinely theirs. No
    surrogate is fitted here and none is carried -- under deviation 1 the screen
    at B is the same shared model for every arm, so what crosses the move from a
    classical arm is its population, its distribution or its dataset, and nothing
    else.

    Args:
        landscape: The instance.
        anchor: Anchor A.
        build: Makes the sampler from the environment and the seed.
        seed: Seeds the sampler.
        rounds: Rounds the campaign runs.
        batch_size: Designs measured per round, and the pool -- a genetic
            algorithm's population *is* its plate.

    Returns:
        The sampler, carrying whatever its rounds at A taught it.
    """
    env = training_environment(landscape, anchor)
    campaign = Campaign(
        landscape=landscape,
        sampler=build(env, seed),
        surrogate=None,
        rounds=rounds,
        batch_size=batch_size,
        pool_size=batch_size,
        environment=env,
        reanchor=False,
    )
    campaign.run()
    return campaign.sampler


@dataclass(frozen=True, slots=True)
class ProbeBudget:
    """Everything about the probe that is a size rather than a decision.

    It exists so the whole path -- campaigns at A, the walk to B, the retrain,
    both screens, the store -- can be exercised end to end at toy scale. Without
    it the only runnable configuration would be the real one, at five hundred
    gradient trainings, and the seams between these pieces would be covered by
    nothing.

    Every default **is** the probe as specified, so a caller that states nothing
    runs the real thing and a caller that shrinks it has said so explicitly at
    the call site. Nothing here is a knob the study varies: the probe reports one
    budget, and a record carries it through
    [_protocol_repr][evogfn.benchmark.transfer._protocol_repr].

    Attributes:
        rounds: Rounds each campaign at A runs.
        near_distance: Substitutions from A to B at the near level.
        far_distance: Substitutions from A to B at the far level. Both distances
            are sizes rather than decisions in exactly the sense this class is
            for -- what they *mean* is fixed by the specification (inside one
            round's budget, and beyond it) and only their magnitudes live here,
            which is what lets a toy landscape shorter than 16 positions still
            exercise both levels.
        batch_size: Designs measured per round, at A and in the plate at B.
        pool_size: Candidates each arm proposes at B before screening.
        steps: Gradient steps per round at A.
        retrain_steps: Gradient steps `plain-retrained` gets at B, or ``None``
            for a whole campaign's worth. Derived rather than defaulted to a
            literal, so shrinking the campaign shrinks the arm that is supposed
            to match it.
        beam_width: Beam width for the per-anchor attainability audit, or
            ``None`` for [anchor_attainable][evogfn.benchmark.transfer.anchor_attainable]'s
            own default.
    """

    rounds: int = TRANSFER_ROUNDS
    near_distance: int = NEAR_DISTANCE
    far_distance: int = FAR_DISTANCE
    batch_size: int = PLATE
    pool_size: int = TRANSFER_POOL
    steps: int = TRANSFER_STEPS
    retrain_steps: int | None = None
    beam_width: int | None = None

    @property
    def retraining_steps(self) -> int:
        """Gradient steps at B for the ceiling arm."""
        return self.rounds * self.steps if self.retrain_steps is None else self.retrain_steps


@dataclass(frozen=True, slots=True)
class SeedPreparation:
    """Everything one seed's campaigns at anchor A produced.

    Built once per seed and reused at both distance levels, which is the saving
    the specification's cost section was reaching for: A does not depend on the
    level, so a training campaign serves both.

    Attributes:
        seed: The seed.
        training_anchor: Anchor A.
        plain: The unconditioned policy at `TRANSFER_HIDDEN_DIM`.
        conditioned: The anchor-conditioned policy at the same width.
        plain_wide: The unconditioned policy at `CAPACITY_HIDDEN_DIM`.
        genetic_reprojected: The genetic algorithm that will carry its
            population.
        genetic_rebuilt: The one that will re-found it. A separate campaign
            because ``carry_population`` is a constructor argument that only
            [reanchored][evogfn.algorithms.baselines.genetic.GeneticAlgorithm.reanchored]
            reads -- so the two campaigns are bit-identical at A, and running
            both is what keeps the rebuilt arm on the documented rebuild path
            (which carries the random stream) rather than on the campaign's
            factory path (which does not).
        cmaes: The relaxation, carrying mean, covariance and both evolution
            paths.
        mlde: The library method, whose state is genuinely anchor-independent.
        surrogate: The one screen every arm at B uses, and the independent
            dataset behind it.
        oracle_calls_at_a: Assays every campaign at A spent between them, the
            shared screen's dataset included.
    """

    seed: int
    training_anchor: Tokens
    plain: TrainedPolicy
    conditioned: TrainedPolicy
    plain_wide: TrainedPolicy
    genetic_reprojected: Sampler
    genetic_rebuilt: Sampler
    cmaes: Sampler
    mlde: Sampler
    surrogate: FittedSurrogate
    oracle_calls_at_a: int


def prepare_seed(
    landscape: EhrlichLandscape, seed: int, budget: ProbeBudget | None = None
) -> SeedPreparation:
    """Run every campaign at anchor A for one seed.

    This is where the probe's compute goes: one dataset for the shared screen,
    three gradient trainings and four classical campaigns per seed, all at the
    same anchor, all reused at both levels.

    Args:
        landscape: The instance.
        seed: The seed. Also fixes anchor A, through
            [feasible_sequence][evogfn.landscapes.ehrlich.EhrlichLandscape.feasible_sequence].
        budget: Sizes, or ``None`` for the probe as specified.

    Returns:
        Everything the round at B will need.
    """
    sizes = budget or ProbeBudget()
    anchor = np.asarray(landscape.feasible_sequence(seed))
    shared = fit_shared_surrogate(
        landscape, anchor, seed=seed, rounds=sizes.rounds, batch_size=sizes.batch_size
    )

    def train(*, hidden_dim: int, anchor_conditioned: bool = False) -> TrainedPolicy:
        return train_policy_at_anchor(
            landscape,
            anchor,
            seed=seed,
            hidden_dim=hidden_dim,
            anchor_conditioned=anchor_conditioned,
            steps=sizes.steps,
            rounds=sizes.rounds,
            batch_size=sizes.batch_size,
        )

    def classical(build: Callable[[MutationEnvironment, int], Sampler]) -> Sampler:
        return run_classical_at_anchor(
            landscape,
            anchor,
            build=build,
            seed=seed,
            rounds=sizes.rounds,
            batch_size=sizes.batch_size,
        )

    plain = train(hidden_dim=TRANSFER_HIDDEN_DIM)
    conditioned = train(hidden_dim=TRANSFER_HIDDEN_DIM, anchor_conditioned=True)
    plain_wide = train(hidden_dim=CAPACITY_HIDDEN_DIM)
    reprojected = classical(lambda env, s: GeneticAlgorithm(env, carry_population=True, seed=s))
    rebuilt = classical(lambda env, s: GeneticAlgorithm(env, carry_population=False, seed=s))
    cmaes = classical(lambda env, s: CMAES(env, repair="greedy", seed=s))
    mlde = classical(lambda env, s: MLDE(env, seed=s))

    campaign_assays = sizes.rounds * sizes.batch_size
    return SeedPreparation(
        seed=seed,
        training_anchor=anchor,
        plain=plain,
        conditioned=conditioned,
        plain_wide=plain_wide,
        genetic_reprojected=reprojected,
        genetic_rebuilt=rebuilt,
        cmaes=cmaes,
        mlde=mlde,
        surrogate=shared,
        oracle_calls_at_a=(
            shared.oracle_calls
            + plain.oracle_calls
            + conditioned.oracle_calls
            + plain_wide.oracle_calls
            # The four classical campaigns, which report nothing back but are
            # charged all the same: a probe that reported only the assays it kept
            # a handle on would understate its own cost.
            + 4 * campaign_assays
        ),
    )


